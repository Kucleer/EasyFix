// 把一天的毫秒数（北京时间）当作 UTC 日期来读，得到 'YYYY-MM-DD'
// 做法：先加 8 小时，再用 UTC 方法取年月日，这样不依赖运行环境的时区
export function beijingDate(now) {
  const shifted = new Date(now.getTime() + 8 * 3600 * 1000)
  return shifted.toISOString().slice(0, 10)
}

// 按日期挑一句：同一天同一句，相邻两天不同
// 算法：日期转成从 2026-01-01 起的天数 n，取 DAILY_LINES[n % 句数]
export function pickDailyLine(dateText) {
  const [y, m, d] = dateText.split('-').map(Number)
  const days = Math.round((Date.UTC(y, m - 1, d) - Date.UTC(2026, 0, 1)) / 86400000)
  const n = ((days % DAILY_LINES.length) + DAILY_LINES.length) % DAILY_LINES.length
  return DAILY_LINES[n]
}
